def build_feature_matrix(metrics_dict: dict, n_steps: int) -> np.ndarray:
    """
    Convert a metrics dict (from generator) into a (n_steps, n_features) array.
    Maps generator keys → FEATURE_NAMES order.
    Fills missing features with zeros.
    """
    matrix = np.zeros((n_steps, N_FEATURES))

    key_map = {
        "memory_usage_bytes": 0,
        "memory_limit_bytes": 1,
        "memory_usage_pct":   2,
        "cpu_usage_cores":    3,
        "cpu_limit_cores":    4,
        "cpu_usage_pct":      5,
        "restart_count":      6,
        "network_rx_bytes":   7,
        "network_tx_bytes":   8,
        "disk_usage_bytes":   9,
        "http_error_rate":   10,
        "http_latency_p99":  11,
    }

    for key, col_idx in key_map.items():
        if key in metrics_dict:
            vals = np.array(metrics_dict[key][:n_steps])
            matrix[:len(vals), col_idx] = vals

    return matrix


def generate_training_data(
    samples_per_class: int = 200,
    n_steps: int = 300,
) -> Tuple[List[np.ndarray], List[int]]:
    """
    Generate synthetic training sequences for all 4 failure classes.
    Returns sequences and their class labels.
    """
    sequences = []
    labels = []

    print(f"[Trainer] Generating {samples_per_class} samples × {N_CLASSES} classes...")

    for class_idx, failure_class in enumerate(FAILURE_CLASSES):
        for i in range(samples_per_class):
            # Generate pattern with slight randomization
            noise_factor = np.random.uniform(0.8, 1.2)
            metrics = generate_single_pattern(failure_class, n_steps, noise_factor)
            matrix = build_feature_matrix(metrics, n_steps)
            sequences.append(matrix)
            labels.append(class_idx)

        print(f"  [{class_idx+1}/{N_CLASSES}] {failure_class}: {samples_per_class} sequences")

    return sequences, labels


def generate_single_pattern(failure_type: str, n_steps: int, noise: float = 1.0) -> dict:
    """Generate one synthetic failure pattern."""
    t = np.arange(n_steps)
    r = np.random.randn

    base_memory = 200 * 1024 * 1024   # 200MB baseline
    limit_memory = 512 * 1024 * 1024  # 512MB limit

    if failure_type == "memory_leak":
        leak_rate = noise * 1.5 * 1024 * 1024  # 1.5MB/step
        memory = base_memory + t * leak_rate + np.abs(np.random.randn(n_steps)) * 5e6
        memory = np.clip(memory, 0, limit_memory)
        cpu = 0.1 + np.random.randn(n_steps) * 0.05 + t * 0.0002 * noise
        error_rate = np.where(memory > 0.85 * limit_memory, 0.3, 0.01)

    elif failure_type == "cpu_throttle":
        memory = base_memory + np.random.randn(n_steps) * 10e6
        # Periodic CPU spikes
        cpu = 0.1 + 0.3 * np.sin(t * 0.2 * noise) + np.random.randn(n_steps) * 0.05
        cpu = np.clip(cpu + np.where(t % 30 < 5, 0.8, 0), 0, 2.0)
        error_rate = np.where(cpu > 0.8, 0.2, 0.02)

    elif failure_type == "cascading_timeout":
        memory = base_memory + np.random.randn(n_steps) * 8e6
        cpu = 0.15 + np.random.randn(n_steps) * 0.03
        # Exponential timeout growth
        error_rate = 0.01 * np.exp(t * 0.015 * noise) + np.random.randn(n_steps) * 0.01
        error_rate = np.clip(error_rate, 0, 1.0)

    elif failure_type == "disk_pressure":
        memory = base_memory + np.random.randn(n_steps) * 10e6
        cpu = 0.12 + np.random.randn(n_steps) * 0.04
        error_rate = 0.01 + np.random.randn(n_steps) * 0.005

    else:
        memory = np.full(n_steps, base_memory)
        cpu = np.full(n_steps, 0.1)
        error_rate = np.full(n_steps, 0.01)

    memory_pct = memory / limit_memory
    cpu_pct = cpu / 0.5  # assume 500m limit

    disk_fill_rate = noise * 50 * 1024 if failure_type == "disk_pressure" else 1024
    disk = np.clip(t * disk_fill_rate + np.random.randn(n_steps) * 1024, 0, 10 * 1024 * 1024)
    latency = 50 + error_rate * 500 + np.random.randn(n_steps) * 10

    return {
        "memory_usage_bytes": memory.tolist(),
        "memory_limit_bytes": np.full(n_steps, limit_memory).tolist(),
        "memory_usage_pct":   memory_pct.tolist(),
        "cpu_usage_cores":    cpu.tolist(),
        "cpu_limit_cores":    np.full(n_steps, 0.5).tolist(),
        "cpu_usage_pct":      cpu_pct.tolist(),
        "restart_count":      np.cumsum(np.random.poisson(0.01, n_steps)).tolist(),
        "network_rx_bytes":   np.abs(np.random.randn(n_steps) * 1e6).tolist(),
        "network_tx_bytes":   np.abs(np.random.randn(n_steps) * 5e5).tolist(),
        "disk_usage_bytes":   disk.tolist(),
        "http_error_rate":    error_rate.tolist(),
        "http_latency_p99":   latency.tolist(),
    }


# ─────────────────────────────────────────────────────────────────────────────
# Normalisation
# ─────────────────────────────────────────────────────────────────────────────

def compute_normalization_stats(
    sequences: List[np.ndarray],
) -> Tuple[np.ndarray, np.ndarray]:
    """Compute per-feature mean and std across all sequences."""
    all_data = np.vstack(sequences)  # (total_steps, n_features)
    means = all_data.mean(axis=0)
    stds  = all_data.std(axis=0) + 1e-8
    return means, stds


# ─────────────────────────────────────────────────────────────────────────────
# Training Loop
# ─────────────────────────────────────────────────────────────────────────────

def train(
    samples_per_class: int = 250,
    window_size: int = 60,
    stride: int = 10,
    batch_size: int = 64,
    epochs: int = 30,
    lr: float = 1e-3,
    val_split: float = 0.2,
    model_dir: str = "neuralops/models",
    device: str = "cpu",
):
    """Full training pipeline."""
    start_time = time.time()
    print("\n" + "=" * 60)
    print("  NeuralOps LSTM Training Pipeline")
    print("=" * 60)

    # ── 1. Generate data ──────────────────────────────────────────
    sequences, labels = generate_training_data(
        samples_per_class=samples_per_class,
        n_steps=300,
    )

    # ── 2. Normalize ──────────────────────────────────────────────
    print("[Trainer] Computing normalization stats...")
    means, stds = compute_normalization_stats(sequences)
    sequences_norm = [(s - means) / stds for s in sequences]
    sequences_norm = [np.clip(s, -5.0, 5.0) for s in sequences_norm]

    # ── 3. Build dataset + split ──────────────────────────────────
    dataset = MetricsDataset(sequences_norm, labels, window_size=window_size, stride=stride)
    val_size   = int(len(dataset) * val_split)
    train_size = len(dataset) - val_size
    train_ds, val_ds = random_split(dataset, [train_size, val_size])

    train_loader = DataLoader(train_ds, batch_size=batch_size, shuffle=True,  num_workers=0)
    val_loader   = DataLoader(val_ds,   batch_size=batch_size, shuffle=False, num_workers=0)

    print(f"[Trainer] Train: {train_size} | Val: {val_size} | Batch: {batch_size}")

    # ── 4. Model ──────────────────────────────────────────────────
    dev = torch.device(device)
    model = NeuralOpsLSTM(window_size=window_size).to(dev)
    print(f"[Trainer] Model: {sum(p.numel() for p in model.parameters()):,} params on {device}")

    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)
    scheduler = ReduceLROnPlateau(optimizer, mode="min", patience=5, factor=0.5)
    criterion_cls  = nn.CrossEntropyLoss()
    criterion_anom = nn.BCELoss()

    # ── 5. Train ──────────────────────────────────────────────────
    best_val_acc = 0.0
    history = {"train_loss": [], "val_loss": [], "val_acc": []}

    os.makedirs(model_dir, exist_ok=True)

    for epoch in range(1, epochs + 1):
        # Train
        model.train()
        total_loss = 0.0
        for x_batch, y_batch in train_loader:
            x_batch = x_batch.to(dev)
            y_batch = y_batch.to(dev)

            optimizer.zero_grad()
            class_probs, anom_score = model(x_batch)

            loss_cls  = criterion_cls(class_probs, y_batch)
            # Anomaly target: 1 if confidence > 0.5 for ANY class
            anom_target = (class_probs.detach().max(dim=1).values > 0.5).float().unsqueeze(1)
            loss_anom = criterion_anom(anom_score, anom_target)

            loss = loss_cls + 0.3 * loss_anom
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            total_loss += loss.item()

        avg_train_loss = total_loss / len(train_loader)

        # Validate
        model.eval()
        val_loss = 0.0
        correct = 0
        total = 0
        with torch.no_grad():
            for x_batch, y_batch in val_loader:
                x_batch = x_batch.to(dev)
                y_batch = y_batch.to(dev)
                class_probs, anom_score = model(x_batch)

                loss_cls = criterion_cls(class_probs, y_batch)
                val_loss += loss_cls.item()

                preds = class_probs.argmax(dim=1)
                correct += (preds == y_batch).sum().item()
                total += y_batch.size(0)

        avg_val_loss = val_loss / len(val_loader)
        val_acc = correct / total
        scheduler.step(avg_val_loss)

        history["train_loss"].append(avg_train_loss)
        history["val_loss"].append(avg_val_loss)
        history["val_acc"].append(val_acc)

        # Save best
        if val_acc > best_val_acc:
            best_val_acc = val_acc
            torch.save({
                "model_state":   model.state_dict(),
                "feature_means": means,
                "feature_stds":  stds,
                "epoch":         epoch,
                "val_acc":       val_acc,
                "failure_classes": FAILURE_CLASSES,
                "feature_names":   FEATURE_NAMES,
            }, f"{model_dir}/lstm_checkpoint.pt")

        if epoch % 5 == 0 or epoch == 1:
            print(f"  Epoch {epoch:3d}/{epochs} | "
                  f"Train Loss: {avg_train_loss:.4f} | "
                  f"Val Loss: {avg_val_loss:.4f} | "
                  f"Val Acc: {val_acc:.2%} | "
                  f"LR: {optimizer.param_groups[0]['lr']:.2e}")

    # ── 6. Save report ────────────────────────────────────────────
    elapsed = time.time() - start_time
    report = {
        "best_val_accuracy": best_val_acc,
        "final_val_accuracy": history["val_acc"][-1],
        "epochs_trained": epochs,
        "training_time_seconds": round(elapsed, 1),
        "samples_per_class": samples_per_class,
        "window_size": window_size,
        "failure_classes": FAILURE_CLASSES,
        "history": history,
    }

    with open(f"{model_dir}/training_report.json", "w") as f:
        json.dump(report, f, indent=2)

    print("\n" + "=" * 60)
    print(f"  Training Complete!")
    print(f"  Best Val Accuracy: {best_val_acc:.2%}")
    print(f"  Time: {elapsed:.1f}s")
    print(f"  Model: {model_dir}/lstm_checkpoint.pt")
    print(f"  Report: {model_dir}/training_report.json")
    print("=" * 60 + "\n")

    return report


