# Dataset
# ─────────────────────────────────────────────────────────────────────────────

class MetricsDataset(Dataset):
    """
    Sliding window dataset over time series metrics.

    Each sample: (window_size, n_features) → label (class index)
    """

    def __init__(
        self,
        sequences: List[np.ndarray],   # list of (T, n_features) arrays
        labels: List[int],             # class index per sequence
        window_size: int = 60,
        stride: int = 10,
    ):
        self.window_size = window_size
        self.samples: List[Tuple[np.ndarray, int]] = []

        for seq, label in zip(sequences, labels):
            # Slide window over full sequence
            T = len(seq)
            for start in range(0, T - window_size + 1, stride):
                window = seq[start : start + window_size]
                self.samples.append((window.astype(np.float32), label))

        print(f"[Dataset] {len(self.samples)} windows from {len(sequences)} sequences")

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        window, label = self.samples[idx]
        return torch.FloatTensor(window), torch.tensor(label, dtype=torch.long)


